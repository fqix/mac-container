import * as fs from 'node:fs';

import * as esbuild from 'esbuild';

const production = process.argv.includes('--production');
const watch = process.argv.includes('--watch');

const common = { bundle: true, minify: production, sourcemap: !production, logLevel: 'info' };

// Webviews are a separate Vite + React project in webview-ui/

const contexts = await Promise.all([
  // Extension host (Node)
  esbuild.context({
    ...common,
    entryPoints: ['src/extension.ts'],
    format: 'cjs',
    platform: 'node',
    target: 'node20',
    outfile: 'dist/extension.js',
    external: ['vscode'],
    // Prefer ESM entries: the UMD build of jsonc-parser loads its modules with a dynamic require esbuild cannot follow
    mainFields: ['module', 'main'],
  }),
  // docker-compatible shim that devcontainers/cli runs as its --docker-path
  esbuild.context({
    ...common,
    entryPoints: ['src/dockerShim/main.ts'],
    format: 'cjs',
    platform: 'node',
    target: 'node20',
    outfile: 'dist/docker-shim.js',
    mainFields: ['module', 'main'],
  }),
]);

// devcontainers/cli ships as one self-contained bundle; copy it next to the extension so it is part of the VSIX.
// run.js clears ELECTRON_RUN_AS_NODE before loading it, so lifecycle commands do not inherit it.
const cliSource = 'node_modules/@devcontainers/cli';
const cliTarget = 'dist/devcontainer-cli';
fs.rmSync(cliTarget, { recursive: true, force: true });
fs.cpSync(cliSource, cliTarget, { recursive: true, filter: (src) => !src.endsWith('.md') });
fs.writeFileSync(
  `${cliTarget}/run.js`,
  "// Generated by esbuild.mjs\ndelete process.env.ELECTRON_RUN_AS_NODE;\nrequire('./devcontainer.js');\n",
);

if (watch) {
  await Promise.all(contexts.map((ctx) => ctx.watch()));
} else {
  await Promise.all(contexts.map((ctx) => ctx.rebuild()));
  await Promise.all(contexts.map((ctx) => ctx.dispose()));
}
