import * as assert from 'assert';

import { parseEnvOutput, resolveContainerEnv, sessionEnvironment } from '../../src/utils/env';

describe('container environment', () => {
  it('parses env output, skipping continuation lines of multi-line values', () => {
    assert.deepStrictEqual(parseEnvOutput('PATH=/usr/bin:/bin\nHOME=/root\nCERT=-----BEGIN\nline two\nEMPTY=\nA=b=c\n'), {
      PATH: '/usr/bin:/bin',
      HOME: '/root',
      CERT: '-----BEGIN',
      EMPTY: '',
      A: 'b=c',
    });
  });

  it('resolves containerEnv references with defaults', () => {
    assert.deepStrictEqual(
      resolveContainerEnv(
        { PATH: '${containerEnv:PATH}:/opt/bin', MODE: '${containerEnv:MODE:dev}', MISSING: '[${containerEnv:NOPE}]', PLAIN: 'x' },
        { PATH: '/usr/bin' },
      ),
      { PATH: '/usr/bin:/opt/bin', MODE: 'dev', MISSING: '[]', PLAIN: 'x' },
    );
  });

  it('writes the container environment for SSH sessions without per-session variables', () => {
    assert.strictEqual(
      sessionEnvironment({ PATH: '/usr/local/bin:/usr/bin', HOME: '/root', HOSTNAME: 'c', JAVA_HOME: '/opt/jdk', TERM: 'xterm' }, { PATH: '/x', EXTRA: '1' }),
      ['# Generated by Apple Container Tools from the container environment; rewritten on every open', 'PATH=/x', 'JAVA_HOME=/opt/jdk', 'EXTRA=1', ''].join('\n'),
    );
  });
});
