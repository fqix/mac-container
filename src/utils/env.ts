// Container environment helpers for SSH sessions and devcontainer.json remoteEnv; free of the vscode API for unit tests

/** Variables that belong to each login session, so they are never pinned for SSH sessions */
const SESSION_VARIABLES = new Set(['HOME', 'USER', 'LOGNAME', 'SHELL', 'PWD', 'OLDPWD', 'SHLVL', 'TERM', '_', 'HOSTNAME', 'MAIL']);

const NAME = /^[A-Za-z_][A-Za-z0-9_]*$/;

/** Parses `env` output; continuation lines of multi-line values are skipped */
export function parseEnvOutput(output: string): Record<string, string> {
  const env: Record<string, string> = {};
  for (const line of output.split('\n')) {
    const i = line.indexOf('=');
    if (i > 0 && NAME.test(line.slice(0, i))) {
      env[line.slice(0, i)] = line.slice(i + 1);
    }
  }
  return env;
}

/** Resolves ${containerEnv:NAME[:default]} in each value against the container's environment */
export function resolveContainerEnv(values: Record<string, string>, containerEnv: Record<string, string>): Record<string, string> {
  return Object.fromEntries(
    Object.entries(values).map(([key, value]) => [
      key,
      String(value).replace(/\$\{containerEnv:([A-Za-z_][A-Za-z0-9_]*)(?::([^}]*))?\}/g, (_m, name: string, fallback?: string) =>
        containerEnv[name] ?? fallback ?? '',
      ),
    ]),
  );
}

/**
 * Content of ~/.ssh/environment: the container's environment plus extra variables, one NAME=value per line.
 * sshd reads it for every session when PermitUserEnvironment is on, since sessions do not inherit the container env.
 */
export function sessionEnvironment(containerEnv: Record<string, string>, extra: Record<string, string> = {}): string {
  const merged = { ...containerEnv, ...extra };
  const lines = ['# Generated by Apple Container Tools from the container environment; rewritten on every open'];
  for (const [key, value] of Object.entries(merged)) {
    if (NAME.test(key) && !SESSION_VARIABLES.has(key) && !value.includes('\n')) {
      lines.push(`${key}=${value}`);
    }
  }
  return lines.join('\n') + '\n';
}
